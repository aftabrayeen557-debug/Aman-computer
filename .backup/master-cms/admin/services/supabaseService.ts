export interface DbWriteResult {
  ok: boolean;
  error?: string;
}

function getClient() {
  if (!isSupabaseConfigured() || !supabase) return null;
  return supabase;
}

const okResult = (): DbWriteResult => ({ ok: true });
const errResult = (error: unknown): DbWriteResult => ({
  ok: false,
  error:
    error && typeof error === 'object' && 'message' in error
      ? String((error as { message: unknown }).message)
      : 'Supabase operation failed or not configured.',
});

export const toIsoTimestamp = (value?: string | null): string => {
  if (!value) return new Date().toISOString();
  const trimmed = value.trim();
  // Handle DD/MM/YYYY [HH:MM AM/PM] format generated by en-GB toLocaleDateString
  const ddmmyyyy = /^(\d{1,2})\/(\d{1,2})\/(\d{4})(?:\s+(.*))?$/.exec(trimmed);
  if (ddmmyyyy) {
    const [, dd, mm, yyyy, rest] = ddmmyyyy;
    const candidate = new Date(`${yyyy}-${mm.padStart(2, '0')}-${dd.padStart(2, '0')}${rest ? ' ' + rest : ''}`);
    if (!Number.isNaN(candidate.getTime())) return candidate.toISOString();
  }
  const parsed = new Date(trimmed);
  if (!Number.isNaN(parsed.getTime())) {
    return parsed.toISOString();
  }
  return new Date().toISOString();
};

