export const dbGetCustomers = async (): Promise<Customer[] | null> => {
  const client = getClient();
  if (!client) return null;
  const { data, error } = await client.from('customers').select('*').order('created_at', { ascending: false });
  if (error) return null;
  return data.map(mapCustomerRow);
};

export const dbUpsertCustomer = async (cust: Customer): Promise<DbWriteResult> => {
  const client = getClient();
  if (!client) return errResult({ message: 'Supabase not configured' });
  const { error } = await client.from('customers').upsert({
    id: cust.id,
    name: cust.name,
    phone: cust.phone,
    email: cust.email || null,
    address: cust.address,
    category: cust.category,
    total_visits: cust.totalVisits,
    total_spent: cust.totalSpent,
    notes: cust.notes || null,
    created_at: toIsoTimestamp(cust.createdAt),
    last_visit_date: toIsoTimestamp(cust.lastVisitDate),
  });
  return error ? errResult(error) : okResult();
};

export const dbDeleteCustomer = async (id: string): Promise<DbWriteResult> => {
  const client = getClient();
  if (!client) return errResult({ message: 'Supabase not configured' });
  const { error } = await client.from('customers').delete().eq('id', id);
  return error ? errResult(error) : okResult();
};

